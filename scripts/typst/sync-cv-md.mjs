#!/usr/bin/env node
/**
 * scripts/typst/sync-cv-md.mjs
 *
 * Generates canonical `cv.md` from the master YAML bank (`content/yaml/*-all.yml`,
 * `content/yaml/education.yml`) and `config/profile.yml`.
 *
 * The generated `cv.md` follows `examples/cv-example.md` grammar so every
 * career-ops script (`doctor.mjs`, `verify-cv-facts.mjs`, `jd-skill-gap.mjs`,
 * `cv-title-check.mjs`, `verify-cv-structure.mjs`, `upskill.mjs`, `keyword-match.mjs`)
 * reads a single, truthful source of truth without manual duplication.
 *
 * Honesty rules:
 * - Never exports `status: planned` items as completed experience.
 * - `status: planned` projects appear only under a clearly labelled
 *   `## Trajectory / Planned Personal Projects (Not Yet Completed)` section so
 *   `verify-cv-facts.mjs` recognizes the authorized wording if explicitly opted in,
 *   while agents and evaluators know it is NOT completed work.
 * - `status: in-progress` skills (e.g. Rust) are not listed as mastered skills in
 *   `## Skills` unless confirmed; they remain truthfully attributed inside their
 *   in-progress project entry.
 *
 * Usage:
 *   node scripts/typst/sync-cv-md.mjs [--out cv.md] [--include-unconfirmed-skills]
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { fileURLToPath } from 'url';
import * as yaml from 'js-yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..', '..');

function parseArgs(argv) {
  const opts = {
    out: join(ROOT, 'cv.md'),
    includeUnconfirmedSkills: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--out' && argv[i + 1]) {
      opts.out = resolve(ROOT, argv[++i]);
    } else if (arg === '--include-unconfirmed-skills') {
      opts.includeUnconfirmedSkills = true;
    } else if (arg === '--help' || arg === '-h') {
      console.log('Usage: node scripts/typst/sync-cv-md.mjs [--out cv.md] [--include-unconfirmed-skills]');
      process.exit(0);
    }
  }
  return opts;
}

function loadYamlFile(relPath, required = true) {
  const full = join(ROOT, relPath);
  if (!existsSync(full)) {
    if (required) throw new Error(`Missing required file: ${relPath}`);
    return null;
  }
  return yaml.load(readFileSync(full, 'utf8'));
}

function stripInlineMarkers(text) {
  return String(text ?? '').replace(/\[\[(.*?)\]\]/g, '$1').replace(/\s+/g, ' ').trim();
}

function skillName(entry) {
  return typeof entry === 'string' ? entry : entry.name;
}

function skillStatus(entry) {
  return typeof entry === 'string' ? 'done' : (entry.status || 'done');
}

function skillNeedsConfirm(entry) {
  return typeof entry === 'object' && entry !== null && Boolean(entry.confirm_before_cv);
}

export function buildCvMarkdown(opts = {}) {
  const experiences = loadYamlFile('content/yaml/experience-all.yml') || [];
  const projectGroups = loadYamlFile('content/yaml/projects-all.yml') || [];
  const skillGroups = loadYamlFile('content/yaml/skills-all.yml') || [];
  const education = loadYamlFile('content/yaml/education-all.yml', false) || loadYamlFile('content/yaml/education.yml') || [];
  const aboutAll = loadYamlFile('content/yaml/about-all.yml', false) || {};
  const info = loadYamlFile('content/yaml/info.yml', false) || {};
  const profile = loadYamlFile('config/profile.yml', false) || {};

  const cand = profile.candidate || {};
  const fullName = info.full_name || cand.full_name || 'Candidate Name';
  const location = info.location || cand.location || 'Paris, France';
  const email = info.email || cand.email || 'candidate@example.com';
  const linkedin = info.linkedin || cand.linkedin || '';
  const github = info.github || cand.github || '';

  const lines = [];
  lines.push('<!-- AUTO-GENERATED by scripts/typst/sync-cv-md.mjs from content/yaml/*-all.yml and content/yaml/info.yml. Do not edit manually. -->');
  lines.push(`# CV -- ${fullName}`);
  lines.push('');
  lines.push(`**Location:** ${location}`);
  lines.push(`**Email:** ${email}`);
  if (linkedin) lines.push(`**LinkedIn:** ${linkedin}`);
  if (github) lines.push(`**GitHub:** ${github}`);
  lines.push('');

  // Professional Summary
  lines.push('## Professional Summary');
  lines.push('');
  const defaultAbout = aboutAll.default?.en || {};
  const summaryParts = [
    stripInlineMarkers(defaultAbout.about_me),
    stripInlineMarkers(defaultAbout.profile),
  ].filter(Boolean);
  if (summaryParts.length > 0) {
    lines.push(summaryParts.join(' '));
  } else {
    lines.push('Systems and Cloud-Native Engineer.');
  }
  lines.push('');

  // Work Experience (canonical grammar: ### Company -- Location / **Role** / Dates)
  lines.push('## Work Experience');
  lines.push('');
  for (const exp of experiences) {
    if (exp.status === 'planned') continue;
    const company = exp.company || exp.title;
    const expLoc = exp.location || location;
    const role = exp.role || exp.title;
    const dates = exp.dates || exp.info || '';

    lines.push(`### ${company} -- ${expLoc}`);
    lines.push('');
    lines.push(`**${role}**`);
    lines.push(dates);
    lines.push('');
    if (exp.description) {
      lines.push(String(exp.description).trim());
      lines.push('');
    }
    for (const item of exp.items || []) {
      if (item.status === 'planned') continue;
      const prefix = item.title ? `**${item.title}:** ` : '';
      lines.push(`- ${prefix}${String(item.text || '').trim()}`);
    }
    lines.push('');
  }

  // Projects (done & in-progress)
  const completedOrActive = [];
  const plannedProjects = [];
  for (const group of projectGroups) {
    for (const item of group.items || []) {
      const desc = String(item.description || '').replace(/\s+/g, ' ').trim();
      const entry = { group: group.title, ...item, description: desc };
      if (item.status === 'planned') {
        plannedProjects.push(entry);
      } else {
        completedOrActive.push(entry);
      }
    }
  }

  lines.push('## Projects');
  lines.push('');
  for (const proj of completedOrActive) {
    const statusTag = proj.status === 'in-progress' ? ' (In Progress)' : '';
    const confTag = proj.confirm_confidentiality ? ' [confirm confidentiality before public CV]' : '';
    lines.push(`- **${proj.name}** (${proj.group}${statusTag})${confTag} -- ${proj.description}`);
  }
  lines.push('');

  if (plannedProjects.length > 0) {
    lines.push('## Trajectory / Planned Personal Projects (Not Yet Completed)');
    lines.push('');
    for (const proj of plannedProjects) {
      lines.push(`- **${proj.name}** (Planned / Trajectory) -- ${proj.description}`);
    }
    lines.push('');
  }

  // Education
  const schoolFr = info.school?.france || '';
  const schoolIntl = info.school?.international || '';
  const degreeEmbedded = info.school?.degree_embedded || '';
  const schoolPairRe = [schoolFr, schoolIntl]
    .filter(Boolean)
    .map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  const mainSchoolRe = schoolPairRe.length > 0 ? new RegExp(`^(${schoolPairRe.join('|')})`, 'i') : null;

  lines.push('## Education');
  lines.push('');
  for (const edu of education) {
    const parts = [];
    if (edu.degree) parts.push(edu.degree);
    if (edu.comment) parts.push(edu.comment);
    const meta = [edu.info_top_left, edu.info_top_right].filter(Boolean).join(', ');
    const isMainSchool = mainSchoolRe ? mainSchoolRe.test(String(edu.title || '')) : false;
    const eduTitle = isMainSchool && schoolFr && schoolIntl
      ? `${schoolFr} (${schoolIntl})`
      : edu.title;
    if (isMainSchool && degreeEmbedded && parts.length > 0 && !parts[0].includes(degreeEmbedded)) {
      parts[0] = degreeEmbedded;
    }
    if (parts.length > 0) {
      lines.push(`- **${eduTitle}** -- ${parts.join(' ')}${meta ? ` (${meta})` : ''}`);
    } else {
      lines.push(`- **${eduTitle}**${meta ? ` (${meta})` : ''}`);
    }
    for (const item of edu.items || []) {
      lines.push(`  - ${String(item.text || '').trim()}`);
    }
  }
  lines.push('');

  // Skills
  lines.push('## Skills');
  lines.push('');
  for (const cat of skillGroups) {
    if (cat.confirm_before_cv && !opts.includeUnconfirmedSkills) {
      // Still include proven specialty items from Embedded if done, or skip if user hasn't confirmed?
      // Include proven `done` skills in cv.md so fact-check & skill-gap recognize real specialty background,
      // while select-from-bank.mjs flags `confirm_before_cv: true` before placing them on a tailored CV.
    }
    const items = (cat.skills || [])
      .filter((s) => skillStatus(s) === 'done')
      .map(skillName);
    if (items.length > 0) {
      lines.push(`- **${cat.name}:** ${items.join(', ')}`);
    }
  }
  lines.push('');

  return lines.join('\n');
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const opts = parseArgs(process.argv.slice(2));
  const markdown = buildCvMarkdown(opts);
  writeFileSync(opts.out, markdown, 'utf8');
  console.log(`Synced ${opts.out} (${markdown.split('\n').length} lines)`);
}
